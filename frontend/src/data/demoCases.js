function makeCase({
  id,
  accession,
  node,
  receivedAt,
  dueAt,
  risk,
  confidence,
  status = 'ready',
  owner = 'Dr. Maya Lin',
  reportKey,
  summaryKey,
  regions,
  triggers = [],
  flags = [],
  decision = null,
  seniorReview = null,
  feedback = null,
  auditTrail = [],
  qcSample = false,
  localSlideId = null,
  analysisSource = null,
}) {
  return {
    id,
    accession,
    diseaseProfileId: BREAST_LYMPH_NODE_HE.id,
    specimen: {
      node,
      siteKey: 'po.disease.axillaryNode',
      stain: BREAST_LYMPH_NODE_HE.stain,
      slideCount: 1,
    },
    receivedAt,
    dueAt,
    owner,
    localSlideId,
    ai: {
      ...DEFAULT_MODEL,
      risk,
      confidence,
      summaryKey,
      reportKey,
      regions,
      flags,
      analysisSource,
      generatedAt: '2026-07-17T07:30:00+08:00',
    },
    workflow: {
      status,
      reviewRequired: triggers.length > 0 || status === 'senior_review',
      reviewTriggers: [...triggers],
      qcSample,
      decision,
      seniorReview,
      lastUpdatedAt: auditTrail.at(-1)?.at || receivedAt,
    },
    feedback: feedback || {
      eligible: status === 'completed',
      status: status === 'completed' ? 'queued' : 'not_eligible',
      version: status === 'completed' ? 'v1' : null,
    },
    auditTrail: [
      audit(receivedAt, 'case_received', 'System', 'po.audit.caseReceived'),
      audit('2026-07-17T07:30:00+08:00', 'ai_triage', DEFAULT_MODEL.name, 'po.audit.aiTriage'),
      ...auditTrail,
    ],
  }
}

